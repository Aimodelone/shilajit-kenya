/**
 * tests/inquiries.test.js — CommonJS
 * Public inquiry API — comprehensive checks.
 * Run via: npm run test:api
 *
 * Uses fresh X-Forwarded-For IPs per test group so rate limits do not
 * interfere between groups. The rate-limit section uses a fixed IP.
 *
 * Cleanup in finally:
 *   - delete all zztest- Inquiry documents
 *   - confirm zztest- Inquiry count is 0
 *   - confirm real (non-zztest-) Inquiry count is unchanged
 */
'use strict';

const Inquiry = require('../models/Inquiry');
const {
  BASE_URL, check, exitWithResults,
  connectDB, disconnectDB, preflight,
} = require('./helpers');

const PATH = '/api/inquiries';

// ── IP helpers ────────────────────────────────────────────────────────────────
function randByte() { return Math.floor(Math.random() * 254) + 1; }
function freshIp()  { return `10.${randByte()}.${randByte()}.${randByte()}`; }

// Fixed IP for rate-limit test group (172.x range never generated by freshIp)
const RATE_LIMIT_IP = '172.16.100.100';

// ── HTTP helpers ──────────────────────────────────────────────────────────────
async function apiPost(bodyRaw, headers = {}) {
  const h = { 'Content-Type': 'application/json', ...headers };
  const res = await fetch(`${BASE_URL}${PATH}`, {
    method: 'POST', headers: h,
    body: typeof bodyRaw === 'string' ? bodyRaw : JSON.stringify(bodyRaw),
    redirect: 'manual',
  });
  let json = null; try { json = await res.json(); } catch {}
  return { status: res.status, json, headers: res.headers };
}

// POST with a fresh random IP
async function post(body, extraHeaders = {}) {
  return apiPost(body, { 'X-Forwarded-For': freshIp(), ...extraHeaders });
}

// POST with a specific IP
async function postIp(body, ip) {
  return apiPost(body, { 'X-Forwarded-For': ip });
}

// POST with raw text body (bypasses JSON.stringify — for invalid-JSON tests)
async function rawPost(text) {
  return apiPost(text, { 'X-Forwarded-For': freshIp() });
}

// Non-POST method with a fresh IP
async function callMethod(method) {
  const noBody = ['GET', 'HEAD', 'DELETE'].includes(method);
  const res = await fetch(`${BASE_URL}${PATH}`, {
    method,
    headers: {
      'Content-Type': 'application/json',
      'X-Forwarded-For': freshIp(),
    },
    body: noBody ? undefined : JSON.stringify({ name: 'zztest-base', phone: '+254712345678', message: 'Test.' }),
    redirect: 'manual',
  });
  let json = null; try { json = await res.json(); } catch {}
  return { status: res.status, json, headers: res.headers };
}

// Base valid contact body
const BASE = { name: 'zztest-base', phone: '+254712345678', message: 'Test inquiry from zztest.' };

// ── Rejection helper ──────────────────────────────────────────────────────────
// Sends a POST with BASE merged with overrides; checks status; verifies NOT stored.
// `searchBy`: 'name' (default) uses a uid name; 'message' uses a uid message.
let rejectN = 0;
async function assertReject(desc, overrides, searchBy = 'name') {
  ++rejectN;
  const uid = `zztest-reject-${rejectN}`;
  let body;
  if (searchBy === 'name') {
    body = { ...BASE, name: uid, ...overrides };
  } else {
    body = { ...BASE, message: uid, ...overrides };
  }
  const r = await post(body);
  check(`${desc} → 400`, r.status === 400, `Got ${r.status}: ${JSON.stringify(r.json)}`);
  const stored = searchBy === 'name'
    ? await Inquiry.findOne({ name: uid })
    : await Inquiry.findOne({ message: uid });
  check(`${desc} NOT stored`, !stored, stored ? `Found: ${stored._id}` : '');
}

// ── main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n=== inquiries.test.js ===\n');

  await preflight();
  await connectDB();

  // Pre-test real (non-zztest) inquiry count — must not change.
  const realCountBefore = await Inquiry.countDocuments({ name: { $not: /^zztest-/ } });

  // Clean up any leftover zztest- documents from previous failed runs.
  await Inquiry.deleteMany({ name: { $regex: '^zztest-' } });

  try {

    // ── Methods and headers ────────────────────────────────────────────────────
    console.log('\n-- Methods and headers --');
    { const r = await callMethod('GET');
      check('GET → 405', r.status === 405, `Got ${r.status}`);
      const allow = r.headers.get('allow') || '';
      check('GET Allow header contains POST', allow.includes('POST'), `Allow: "${allow}"`); }
    { const r = await callMethod('PUT');
      check('PUT → 405', r.status === 405, `Got ${r.status}`); }
    { const r = await callMethod('DELETE');
      check('DELETE → 405', r.status === 405, `Got ${r.status}`); }
    { const r = await apiPost(BASE, {
        'Content-Type': 'text/plain',
        'X-Forwarded-For': freshIp(),
      });
      check('POST text/plain → 415', r.status === 415, `Got ${r.status}`); }
    { const r = await post(BASE);
      check('successful POST has Cache-Control no-store',
        (r.headers.get('cache-control') || '').includes('no-store'),
        `Cache-Control: "${r.headers.get('cache-control')}"`); }

    // ── Valid input ────────────────────────────────────────────────────────────
    console.log('\n-- Valid input --');

    { const r = await post({ name: 'zztest-contact-1', phone: '+254712345678', message: 'Contact msg.' });
      check('contact with name+phone+message → 201', r.status === 201, `Got ${r.status}: ${JSON.stringify(r.json)}`);
      const keys = Object.keys(r.json || {});
      check('body is exactly { success: true }',
        keys.length === 1 && r.json.success === true,
        `Got: ${JSON.stringify(r.json)}`);
      const stored = await Inquiry.findOne({ name: 'zztest-contact-1' });
      check('stored document exists', !!stored, 'Not found');
      check('stored read = false', stored?.read === false, `Got read=${stored?.read}`);
      check('stored type = "contact"', stored?.type === 'contact', `Got type="${stored?.type}"`); }

    { const r = await post({ name: 'zztest-email-only', email: 'zztest@example.com', message: 'Email only.' });
      check('email only → 201', r.status === 201, `Got ${r.status}`); }

    { const r = await post({ name: 'zztest-both', phone: '+254712345678', email: 'zztest@example.com', message: 'Both.' });
      check('phone and email both → 201', r.status === 201, `Got ${r.status}`); }

    { const r = await post({
        name: 'zztest-order-1', phone: '+254712345678', message: 'Order message.',
        type: 'order', productName: 'Shilajit Resin', quantity: 2,
      });
      check('type "order" with productName+quantity → 201', r.status === 201, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: 'zztest-order-1' });
      check('stored type = "order"', stored?.type === 'order', `Got "${stored?.type}"`);
      check('stored quantity = 2', stored?.quantity === 2, `Got ${stored?.quantity}`); }

    { const r = await post({ name: 'zztest-source', phone: '+254712345678', message: 'Source page.', sourcePage: '/shop' });
      check('sourcePage "/shop" → 201', r.status === 201, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: 'zztest-source' });
      check('stored sourcePage = "/shop"', stored?.sourcePage === '/shop', `Got "${stored?.sourcePage}"`); }

    { const r = await post({ name: 'zztest-email-case', email: 'UPPERCASE@EXAMPLE.COM', message: 'Lowercase email.' });
      check('email uppercase → 201', r.status === 201, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: 'zztest-email-case' });
      check('stored email is lowercased', stored?.email === 'uppercase@example.com', `Got "${stored?.email}"`); }

    // ── Rejections ─────────────────────────────────────────────────────────────
    console.log('\n-- Rejections --');
    await assertReject('no phone and no email',     { phone: undefined, email: undefined });
    await assertReject('phone and email both ""',   { phone: '', email: '' });
    await assertReject('name ""',                   { name: '' }, 'message');
    await assertReject('message ""',                { message: '' });
    await assertReject('message 2001 chars',        { message: 'a'.repeat(2001) });
    await assertReject('name 121 chars',            { name: 'z'.repeat(121) }, 'message');
    await assertReject('phone "abc"',               { phone: 'abc' });
    await assertReject('email "not-an-email"',      { email: 'not-an-email' });
    await assertReject('quantity 0',                { quantity: 0 });
    await assertReject('quantity 1001',             { quantity: 1001 });
    await assertReject('quantity "5" (string)',     { quantity: '5' });
    await assertReject('quantity 1.5 (float)',      { quantity: 1.5 });
    await assertReject('type "admin"',              { type: 'admin' });
    await assertReject('sourcePage "https://evil.example"', { sourcePage: 'https://evil.example' });
    await assertReject('sourcePage "//evil.example"',       { sourcePage: '//evil.example' });
    await assertReject('sourcePage "/ok\\\\bad"',           { sourcePage: '/ok\\bad' });
    await assertReject('sourcePage "javascript:alert(1)"',  { sourcePage: 'javascript:alert(1)' });
    await assertReject('message "<script>alert(1)</script>"', { message: '<script>alert(1)</script>' });
    await assertReject('message "<b>hi</b>"',               { message: '<b>hi</b>' });
    await assertReject('name "Zz <img src=x ...>"',         { name: 'Zz <img src=x onerror=alert(1)>' }, 'message');
    await assertReject('message "click javascript:alert(1)"', { message: 'click javascript:alert(1)' });
    await assertReject('productName "<script>"',            { productName: '<script>' });

    // ── Body handling ──────────────────────────────────────────────────────────
    console.log('\n-- Body handling --');
    { const r = await post([{ name: 'zztest-arr', phone: '+254', message: 'x' }]);
      check('JSON array → 400', r.status === 400, `Got ${r.status}`); }
    { const r = await rawPost('this is { not valid json');
      check('Invalid JSON text → 400', r.status === 400, `Got ${r.status}`); }
    { const r = await post('hello');
      check('JSON string "hello" → 400', r.status === 400, `Got ${r.status}`); }
    { const r = await post(null);
      check('body "null" → 400', r.status === 400, `Got ${r.status}`); }

    // ── Edge case: plain "<" is accepted ─────────────────────────────────────
    console.log('\n-- Edge case --');
    { const r = await post({ name: 'zztest-lt', phone: '+254712345678', message: 'I need 2 < 3 bottles' });
      check('message "I need 2 < 3 bottles" → 201', r.status === 201, `Got ${r.status}`); }

    // ── Mass assignment ────────────────────────────────────────────────────────
    console.log('\n-- Mass assignment --');
    { const fakeId = '507f1f77bcf86cd799439011';
      const r = await post({
        _id: fakeId, read: true, createdAt: '2000-01-01T00:00:00.000Z', hacker: true,
        name: 'zztest-mass', phone: '+254712345678', message: 'Mass assignment test.',
      });
      check('mass assignment → 201', r.status === 201, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: 'zztest-mass' });
      check('stored read = false (not hijacked)', stored?.read === false, `Got ${stored?.read}`);
      check('stored _id is server-generated', stored?._id.toString() !== fakeId, `Got _id="${stored?._id}"`);
      check('no hacker field in stored document', !('hacker' in (stored?.toObject() || {})), 'hacker field found!'); }

    // ── Honeypot ───────────────────────────────────────────────────────────────
    console.log('\n-- Honeypot --');
    { const uid = `zztest-honeypot-${Date.now()}`;
      const r = await post({ name: uid, phone: '+254712345678', message: 'Spam.', website: 'http://spam.example' });
      check('website "http://spam.example" → 200', r.status === 200, `Got ${r.status}`);
      check('honeypot response is { success: true }',
        r.json?.success === true && Object.keys(r.json).length === 1,
        `Got: ${JSON.stringify(r.json)}`);
      const stored = await Inquiry.findOne({ name: uid });
      check('honeypot: nothing stored', !stored, stored ? `Found: ${stored._id}` : ''); }

    { const uid = `zztest-honeypot2-${Date.now()}`;
      const r = await post({ name: uid, phone: '+254712345678', message: 'Spam.', extra_note: 'spam' });
      check('extra_note "spam" → 200', r.status === 200, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: uid });
      check('extra_note honeypot: nothing stored', !stored, stored ? `Found: ${stored._id}` : ''); }

    { const r = await post({ name: 'zztest-hp-empty', phone: '+254712345678', message: 'Legit.', website: '', extra_note: '' });
      check('empty honeypots treated as normal request → 201', r.status === 201, `Got ${r.status}`); }

    // ── Time check ─────────────────────────────────────────────────────────────
    console.log('\n-- Time check --');
    { const uid = `zztest-time-now-${Date.now()}`;
      const r = await post({ name: uid, phone: '+254712345678', message: 'Too fast.', elapsedMs: 500 });
      check('elapsedMs = 500 → 200 (bot)', r.status === 200, `Got ${r.status}`);
      const stored = await Inquiry.findOne({ name: uid });
      check('elapsedMs=500: nothing stored', !stored, stored ? 'Found!' : ''); }

    { const r = await post({ name: 'zztest-time-future', phone: '+254712345678', message: 'Future ts ignored.', formStartedAt: Date.now() + 60000, elapsedMs: 10000 });
      check('future formStartedAt is ignored → 201', r.status === 201, `Got ${r.status}`); }

    { const r = await post({ name: 'zztest-time-ok', phone: '+254712345678', message: 'Normal.', elapsedMs: 10000 });
      check('elapsedMs = 10000 → 201', r.status === 201, `Got ${r.status}`); }

    { const r = await post({ name: 'zztest-time-none', phone: '+254712345678', message: 'No ts.' });
      check('no elapsedMs → 201', r.status === 201, `Got ${r.status}`); }

    // ── Rate limit ─────────────────────────────────────────────────────────────
    console.log('\n-- Rate limit --');
    // Use a fixed, never-reused IP for this group.
    const rlBody = { name: 'zztest-rl', phone: '+254712345678', message: 'Rate limit test.' };
    const r1 = await postIp({ ...rlBody, name: 'zztest-rl-1' }, RATE_LIMIT_IP);
    check('rate limit request 1 → 201', r1.status === 201, `Got ${r1.status}`);
    const r2 = await postIp({ ...rlBody, name: 'zztest-rl-2' }, RATE_LIMIT_IP);
    check('rate limit request 2 → 201', r2.status === 201, `Got ${r2.status}`);
    const r3 = await postIp({ ...rlBody, name: 'zztest-rl-3' }, RATE_LIMIT_IP);
    check('rate limit request 3 → 201', r3.status === 201, `Got ${r3.status}`);
    const r4 = await postIp({ ...rlBody, name: 'zztest-rl-4' }, RATE_LIMIT_IP);
    check('rate limit request 4 → 429', r4.status === 429, `Got ${r4.status}`);
    const retryAfter = r4.headers.get('retry-after') || '';
    check('429 has Retry-After header', retryAfter !== '', `Retry-After: "${retryAfter}"`);
    // Different IP must still succeed
    const r5 = await postIp({ ...rlBody, name: 'zztest-rl-other' }, freshIp());
    check('different IP → 201', r5.status === 201, `Got ${r5.status}`);

    // ── Oversize body ──────────────────────────────────────────────────────────
    console.log('\n-- Oversize body --');
    { const bigBody = JSON.stringify({ name: 'zztest-big', phone: '+254712345678', message: 'x'.repeat(25000) });
      const r = await rawPost(bigBody);
      check('30KB body → 413 or 400', r.status === 413 || r.status === 400, `Got ${r.status}`);
      check('30KB body not 500 or 201', r.status !== 500 && r.status !== 201, `Got ${r.status}`); }

    // ── No data leak ───────────────────────────────────────────────────────────
    console.log('\n-- No data leak --');
    { const r = await post({ name: 'zztest-leak', phone: 'abc', message: 'x' });
      const body = JSON.stringify(r.json || {});
      check('400 body has no stack trace ("    at " pattern)',
        !/\s{4}at\s/.test(body) && !body.includes('\n    at '),
        `Found stack trace in: ${body.substring(0, 200)}`);
      check('400 body has no "mongoose" word',
        !body.toLowerCase().includes('mongoose'),
        `Found "mongoose" in: ${body.substring(0, 200)}`); }

  } finally {
    // ── Cleanup ────────────────────────────────────────────────────────────────
    console.log('\n-- Cleanup --');
    await Inquiry.deleteMany({ name: { $regex: '^zztest-' } });
    const zzCount = await Inquiry.countDocuments({ name: { $regex: '^zztest-' } });
    check('zztest- Inquiry count is 0 after cleanup', zzCount === 0, `Got ${zzCount}`);

    const realCountAfter = await Inquiry.countDocuments({ name: { $not: /^zztest-/ } });
    check('real inquiry count unchanged', realCountAfter === realCountBefore,
      `Before=${realCountBefore} After=${realCountAfter}`);

    await disconnectDB();
  }

  exitWithResults();
}

main().catch(e => { console.error('Unhandled:', e.message); process.exit(1); });
